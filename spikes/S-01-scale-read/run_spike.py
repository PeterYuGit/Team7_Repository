"""Runs spike S-01 and writes results.csv and results.md.

Usage (macOS or Linux, Python 3.8+, no extra packages):
    python3 run_spike.py

Each trial opens a fresh pseudo-terminal (a fake serial port), starts the
simulated scale on one end and reads it with scale_reader on the other.
"""

import csv
import os
import statistics
import time
import tty

from scale_sim import SimulatedScale
from scale_reader import read_stable_weight, ScaleUnavailable

TEST_WEIGHTS = [0.50, 1.00, 2.00, 3.00, 5.00, 5.10, 12.00]   # lb; Table 3.1 / FR-08 boundaries
TRIALS_PER_WEIGHT = 15
DISCONNECT_TRIALS = 20
FR01_TOLERANCE = 0.05     # FR-01 acceptance: +/- 0.05 lb
FLAG_LIMIT = 5.0          # FR-08: flag when weight > 5.0 lb
QR01_BUDGET_S = 3.0       # QR-01: recommendation within 3 s


def one_trial(true_weight, seed, stop_after=None):
    master, slave = os.openpty()
    tty.setraw(slave)
    scale = SimulatedScale(master, true_weight, stop_after=stop_after, seed=seed)
    t0 = time.monotonic()
    scale.start()
    try:
        weight, stats = read_stable_weight(slave)
        outcome, reason = "read", ""
    except ScaleUnavailable as e:
        weight, stats = None, {"lines": 0, "rejected": 0, "unstable": 0}
        outcome, reason = "manual_fallback", e.reason
    elapsed = time.monotonic() - t0
    scale.stop()
    os.close(master)
    os.close(slave)
    return weight, stats, outcome, reason, elapsed


def pct(values, p):
    values = sorted(values)
    k = max(0, min(len(values) - 1, round(p / 100 * (len(values) - 1))))
    return values[k]


def main():
    rows = []
    seed = 1000
    for w in TEST_WEIGHTS:
        for _ in range(TRIALS_PER_WEIGHT):
            seed += 1
            weight, stats, outcome, reason, elapsed = one_trial(w, seed)
            rows.append({"kind": "normal", "true_lb": w, "read_lb": weight,
                         "outcome": outcome, "reason": reason,
                         "seconds": round(elapsed, 3), **stats})
    for i in range(DISCONNECT_TRIALS):
        seed += 1
        # half unplugged before sending anything, half unplugged mid-settle
        stop_after = 0 if i % 2 == 0 else 3
        weight, stats, outcome, reason, elapsed = one_trial(2.00, seed, stop_after=stop_after)
        rows.append({"kind": f"disconnect_after_{stop_after}", "true_lb": 2.00,
                     "read_lb": weight, "outcome": outcome, "reason": reason,
                     "seconds": round(elapsed, 3), **stats})

    with open("results.csv", "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)

    normal = [r for r in rows if r["kind"] == "normal"]
    reads = [r for r in normal if r["outcome"] == "read"]
    errors = [abs(r["read_lb"] - r["true_lb"]) for r in reads]
    within = sum(1 for e in errors if e <= FR01_TOLERANCE + 1e-9)
    lat = [r["seconds"] for r in reads]
    total_lines = sum(r["lines"] for r in normal)
    garbled = sum(r["rejected"] for r in normal)
    disc = [r for r in rows if r["kind"].startswith("disconnect")]
    disc_ok = sum(1 for r in disc if r["outcome"] == "manual_fallback")
    disc_t = [r["seconds"] for r in disc]

    def flag_rate(true_w):
        rs = [r for r in reads if r["true_lb"] == true_w]
        return sum(1 for r in rs if r["read_lb"] > FLAG_LIMIT), len(rs)

    f500, n500 = flag_rate(5.00)
    f510, n510 = flag_rate(5.10)

    md = []
    md.append("# S-01 measured results\n")
    md.append(f"Generated by run_spike.py on {time.strftime('%Y-%m-%d %H:%M')}.\n")
    md.append("| Measure | Result |")
    md.append("|---|---|")
    md.append(f"| Normal trials | {len(normal)} ({TRIALS_PER_WEIGHT} each at {', '.join(f'{w:.2f}' for w in TEST_WEIGHTS)} lb) |")
    md.append(f"| Trials that returned a weight | {len(reads)} / {len(normal)} |")
    md.append(f"| Within FR-01 tolerance (+/- {FR01_TOLERANCE} lb) | {within} / {len(reads)} |")
    md.append(f"| Max absolute error | {max(errors):.3f} lb |")
    md.append(f"| Mean absolute error | {statistics.mean(errors):.3f} lb |")
    md.append(f"| Time to stable weight: median / p95 / max | {statistics.median(lat):.2f} s / {pct(lat, 95):.2f} s / {max(lat):.2f} s |")
    md.append(f"| Share of QR-01's 3 s budget used (p95) | {pct(lat, 95) / QR01_BUDGET_S:.0%} |")
    md.append(f"| Garbled lines received and safely ignored | {garbled} of {total_lines} lines |")
    md.append(f"| Disconnect trials that fell back to manual entry (FR-02) | {disc_ok} / {len(disc)} |")
    md.append(f"| Time to detect disconnect: median / max | {statistics.median(disc_t):.2f} s / {max(disc_t):.2f} s |")
    md.append(f"| 5.00 lb book read as over 5.0 lb (would be flagged by FR-08) | {f500} / {n500} |")
    md.append(f"| 5.10 lb book read as over 5.0 lb (correctly flagged) | {f510} / {n510} |")
    md.append("")
    with open("results.md", "w") as f:
        f.write("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
